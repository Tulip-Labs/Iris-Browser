//! Build step: Iris's list of about 100,000 ad and tracker domains (a JSON
//! array, from src/shield-domains.json.gz) into a Zig source file of native
//! arrays: the usable domains, lowercased, sorted, so Iris finds one by
//! binary search with nothing to read or build when it starts.
//!   domains <list.json> <out.zig>
const std = @import("std");
const rules = @import("rules");

pub fn main() !void {
    var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const args = try std.process.argsAlloc(a);
    const json = try std.fs.cwd().readFileAlloc(a, args[1], 64 << 20);
    const list = try std.json.parseFromSliceLeaky([]const []const u8, a, json, .{});
    var keep: std.ArrayList([]const u8) = .empty;
    for (list) |d| {
        const l = try std.ascii.allocLowerString(a, d);
        if (rules.usable(l)) try keep.append(a, l);
    }
    std.sort.pdq([]const u8, keep.items, {}, struct {
        fn f(_: void, x: []const u8, y: []const u8) bool {
            return std.mem.order(u8, x, y) == .lt;
        }
    }.f);
    var out: std.ArrayList(u8) = .empty;
    try out.appendSlice(a, "//! Generated by tools/domains.zig from shield-domains.json.gz: do not edit.\n");
    try out.appendSlice(a, "/// Iris's ad and tracker domains, lowercased and sorted\npub const list = [_][]const u8{\n");
    var prev: []const u8 = "";
    for (keep.items) |d| {
        if (std.mem.eql(u8, d, prev)) continue;
        prev = d;
        try out.appendSlice(a, "    \"");
        try out.appendSlice(a, d);
        try out.appendSlice(a, "\",\n");
    }
    try out.appendSlice(a, "};\n");
    try std.fs.cwd().writeFile(.{ .sub_path = args[2], .data = out.items });
}
