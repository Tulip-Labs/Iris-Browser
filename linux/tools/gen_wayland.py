#!/usr/bin/env python3
"""Wayland protocol XML -> Odin, the way wayland-scanner makes C.

  gen_wayland.py OUT.odin PROTOCOL.xml...

For each interface: its wl_interface table (the same bytes wayland-scanner
emits, so libwayland-client can marshal it), an opaque handle type, one
procedure per request (through wl_proxy_marshal_array_flags: no C varargs),
a listener struct for its events and add_listener, and its enums as
constants. The output is committed; CI checks it is what this script makes.
"""
import sys
import xml.etree.ElementTree as ET

KEYWORDS = {"proc", "map", "context", "string", "type", "struct", "union", "enum", "in", "not_in",
            "distinct", "dynamic", "bit_set", "matrix", "cast", "transmute", "auto_cast", "when",
            "where", "defer", "using", "package", "import", "foreign", "return", "or_else", "or_return",
            "for", "if", "else", "switch", "case", "break", "continue", "fallthrough", "size_of",
            "align_of", "offset_of", "type_of", "typeid", "any", "rawptr", "nil", "true", "false"}


def ident(n):
    return n + "_" if n in KEYWORDS else n


def tname(iface):
    """wl_surface -> Wl_Surface"""
    return "_".join(p[:1].upper() + p[1:] for p in iface.split("_"))


def odin_type(arg, known):
    t = arg.get("type")
    if t == "int" or t == "fd":
        return "i32"
    if t == "uint":
        return "u32"
    if t == "fixed":
        return "Fixed"
    if t == "string":
        return "cstring"
    if t == "array":
        return "^Array"
    if t in ("object", "new_id"):
        i = arg.get("interface")
        return "^" + tname(i) if i and i in known else "rawptr"
    raise ValueError(t)


def sig_char(arg):
    t = arg.get("type")
    null = "?" if arg.get("allow-null") == "true" else ""
    return null + {"int": "i", "uint": "u", "fixed": "f", "string": "s", "object": "o",
                   "array": "a", "fd": "h"}.get(t, "n" if arg.get("interface") else "sun")


def gen(paths):
    ifaces = []
    for p in paths:
        root = ET.parse(p).getroot()
        for i in root.findall("interface"):
            ifaces.append(i)
    known = {i.get("name") for i in ifaces}
    inits = []
    out = ["// Generated by tools/gen_wayland.py from the protocol XML. Do not edit.",
           "package wl", ""]
    for i in ifaces:
        name = i.get("name")
        T = tname(name)
        ver = i.get("version")
        reqs = i.findall("request")
        evs = i.findall("event")
        out.append(f"// ---- {name} (version {ver})")
        out.append(f"{T} :: struct {{}}")

        def messages(kind, msgs):
            if not msgs:
                return "nil"
            lines = []
            for k, m in enumerate(msgs):
                args = m.findall("arg")
                since = m.get("since")
                sig = (since if since and since != "1" else "") + "".join(sig_char(a) for a in args)
                types = []
                for a in args:
                    if a.get("type") == "new_id" and not a.get("interface"):
                        types += ["nil", "nil", "nil"]
                    elif a.get("type") in ("object", "new_id") and a.get("interface") in known:
                        types.append(f"&{a.get('interface')}_interface")
                    else:
                        types.append("nil")
                tv = f"_{name}_{kind}_{k}_types"
                if types:
                    # filled by _init_types: interfaces refer to each other in
                    # cycles, which Odin's global initializers do not allow
                    out.append(f"@(private) {tv}: [{len(types)}]^Interface")
                    for ti, tt in enumerate(types):
                        if tt != "nil":
                            inits.append(f"\t{tv}[{ti}] = {tt}")
                    lines.append(f'\t{{"{m.get("name")}", "{sig}", &{tv}[0]}},')
                else:
                    lines.append(f'\t{{"{m.get("name")}", "{sig}", nil}},')
            arr = f"_{name}_{kind}"
            out.append(f"@(private) {arr} := [{len(msgs)}]Message{{")
            out.extend(lines)
            out.append("}")
            return f"&{arr}[0]"

        rq = messages("requests", reqs)
        ev = messages("events", evs)
        out.append(f'{name}_interface: Interface = {{"{name}", {ver}, {len(reqs)}, {rq}, {len(evs)}, {ev}}}')

        # requests
        for op, m in enumerate(reqs):
            args = m.findall("arg")
            destructor = m.get("type") == "destructor"
            new = [a for a in args if a.get("type") == "new_id"]
            params = [f"self: ^{T}"]
            body = []
            n = 0
            ret = ""
            iface_expr = "nil"
            ver_expr = "proxy_get_version(cast(^Proxy)self)"
            for a in args:
                an = ident(a.get("name"))
                t = a.get("type")
                if t == "new_id" and not a.get("interface"):
                    params += ["iface: ^Interface", "version: u32"]
                    body.append(f"args[{n}].s = iface.name")
                    body.append(f"args[{n+1}].u = version")
                    body.append(f"args[{n+2}].o = nil")
                    n += 3
                    iface_expr, ver_expr, ret = "iface", "version", "rawptr"
                    continue
                if t == "new_id":
                    ni = a.get("interface")
                    body.append(f"args[{n}].o = nil")
                    n += 1
                    if ni in known:
                        iface_expr, ret = f"&{ni}_interface", "^" + tname(ni)
                    else:
                        iface_expr, ret = "nil", "rawptr"
                    continue
                ot = odin_type(a, known)
                params.append(f"{an}: {ot}")
                field = {"i32": "i", "u32": "u", "Fixed": "f", "cstring": "s", "^Array": "a"}.get(ot, "o")
                if t == "fd":
                    field = "h"
                val = an if field != "o" else f"rawptr({an})"
                body.append(f"args[{n}].{field} = {val}")
                n += 1
            flags = "MARSHAL_FLAG_DESTROY" if destructor else "0"
            sig = ", ".join(params)
            rtype = f" -> {ret}" if ret else ""
            out.append(f"{name}_{m.get('name')} :: proc \"contextless\" ({sig}){rtype} {{")
            out.append(f"\targs: [{max(n, 1)}]Argument")
            for b in body:
                out.append("\t" + b)
            call = (f"proxy_marshal_array_flags(cast(^Proxy)self, {op}, {iface_expr}, {ver_expr}, {flags}, &args[0])")
            if ret:
                out.append(f"\treturn cast({ret}){call}")
            else:
                out.append(f"\t{call}")
            out.append("}")

        # events
        if evs:
            out.append(f"{T}_Listener :: struct {{")
            for m in evs:
                ps = ["data: rawptr", f"self: ^{T}"]
                for a in m.findall("arg"):
                    ps.append(f"{ident(a.get('name'))}: {odin_type(a, known)}")
                out.append(f"\t{ident(m.get('name'))}: proc \"c\" ({', '.join(ps)}),")
            out.append("}")
            out.append(f"{name}_add_listener :: proc \"contextless\" (self: ^{T}, l: ^{T}_Listener, data: rawptr) -> i32 {{")
            out.append("\treturn proxy_add_listener(cast(^Proxy)self, cast(rawptr)l, data)")
            out.append("}")
        if not any(m.get("type") == "destructor" for m in reqs) and name != "wl_display":
            out.append(f"{name}_destroy :: proc \"contextless\" (self: ^{T}) {{ proxy_destroy(cast(^Proxy)self) }}")
        out.append(f"{name}_set_user_data :: proc \"contextless\" (self: ^{T}, d: rawptr) {{ proxy_set_user_data(cast(^Proxy)self, d) }}")
        out.append(f"{name}_get_user_data :: proc \"contextless\" (self: ^{T}) -> rawptr {{ return proxy_get_user_data(cast(^Proxy)self) }}")
        out.append(f"{name}_get_version :: proc \"contextless\" (self: ^{T}) -> u32 {{ return proxy_get_version(cast(^Proxy)self) }}")

        # enums
        for e in i.findall("enum"):
            en = f"{name}_{e.get('name')}".upper()
            for en_ in e.findall("entry"):
                out.append(f"{en}_{en_.get('name').upper()} :: {en_.get('value')}")
        out.append("")
    out.append("/// the argument types of every message (before main runs)")
    out.append("@(init, private)")
    out.append("_init_types :: proc \"contextless\" () {")
    out.extend(inits)
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    open(sys.argv[1], "w").write(gen(sys.argv[2:]))
